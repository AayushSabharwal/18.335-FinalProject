# Generate benchmark matrices: run the FreeFEM stability scripts inside the
# freefem/freefem docker image and convert the assembled matrices into
# stacked-pencil [J; M] Matrix Market files that run_benchmark.jl consumes.
#
#   julia --project=. bench/gen_fem_matrices.jl                  # all jobs
#   julia --project=. bench/gen_fem_matrices.jl cavity cylinder  # subset
#   julia --project=. bench/gen_fem_matrices.jl cavity:1000      # one case
#   julia --project=. bench/gen_fem_matrices.jl --skip-ff ...    # only (re)convert
#
# For each (geometry, Re) the script writes a wrapper .edp
# (TestEnv/fem/run_<job>.edp) that defines the parameter block and includes
# bench/<geometry>.edp — FreeFEM 4.12 has no getARGV(), so parameters are
# injected textually. FreeFEM writes J.mtx/M.mtx (via savemtx) plus bnd.txt
# to TestEnv/fem/<key>_<tag>_Re<Re>/ and the pencil lands in matrices/fem/.
#
# Stability notes:
#   cavity   Re_c ~ 8000    leading complex pair approaches the axis
#   cylinder Re_c ~ 46-47   Hopf pair crosses the axis (vortex shedding)
#   channel  Re_c = 5772    Tollmien--Schlichting; alpha=1 neutral ~5775

using Printf

include(joinpath(@__DIR__, "make_fem_matrices.jl"))

const REPO  = abspath(joinpath(@__DIR__, ".."))
const IMAGE = get(ENV, "FREEFEM_IMAGE", "freefem/freefem:latest")
const FEMDIR = joinpath("TestEnv", "fem")
const MATDIR = joinpath("matrices", "fem")

# header = FreeFEM declaration lines defining geometry/mesh params.
# Re convention: cavity/cylinder — U0·L/ν with U0=L=D=1; channel — U_cl·h/ν.
const JOBS = [
    (key = "cavity", edp = "stability_cavity.edp", tag = "N16",
     params = ["int N = 16;"],
     Res = [1000, 4000, 8000]),
    (key = "cylinder", edp = "stability_cylinder.edp", tag = "D1",
     params = ["int nc = 24;", "int ni = 8;", "int nt = 24;",
               "real xin = -6.;", "real xout = 18.;", "real yw = 6.;",
               "real rc = 0.5;"],
     Res = [60, 150, 300]),
    (key = "channel", edp = "stability_channel.edp", tag = "L2piN16",
     params = ["int NX = 24;", "int N = 16;", "real L = 2*pi;"],
     Res = [5000, 6000, 10000]),
]

refmt(Re) = isinteger(Re) ? string(Int(Re)) : string(Re)

"""Parameter block + include line for one job."""
function wrapper_edp(job, Re, outdir)
    join(vcat(
        "// generated by bench/gen_fem_matrices.jl — do not edit",
        job.params,
        ["real Re     = $Re;",
         "real U0     = 1.0;",
         "real epsP   = 1e-8;",
         "int  maxIt  = 30;",
         "real nwtol  = 1e-10;",
         "real sigRef = 0.0;",
         "int  nev    = 10;",
         "string outdir = \"$outdir\";",
         "include \"/work/bench/$(job.edp)\";",
         ""],
    ), "\n")
end

function run_freefem(runfile, logfile)
    mkpath(dirname(abspath(logfile)))
    cmd = `docker run --rm -v $REPO:/work -w /work $IMAGE
           FreeFem++ $runfile -nw`
    open(logfile, "w") do io
        run(pipeline(cmd, stdout = io, stderr = io))
    end
    return nothing
end

function run_job(job, Re; skip_ff = false)
    key = job.key * "_" * job.tag * "_Re" * refmt(Re)
    indir = joinpath(FEMDIR, key)
    runfile = joinpath(FEMDIR, "run_" * key * ".edp")
    logfile = joinpath(FEMDIR, "log_" * key * ".txt")
    mtxpath = joinpath(MATDIR, "fem_" * key * ".mtx")

    if !skip_ff
        mkpath(joinpath(REPO, FEMDIR))
        write(joinpath(REPO, runfile), wrapper_edp(job, Re, indir))
        println(stderr, "== $key: FreeFem++ ($(job.edp)) -> $indir")
        run_freefem(runfile, logfile)
    end
    isfile(joinpath(REPO, indir, "J.mtx")) ||
        error("no J.mtx in $indir — see log $logfile")
    write_pencil_mtx(joinpath(REPO, indir), joinpath(REPO, mtxpath))
    return nothing
end

# ---- tiny CLI ------------------------------------------------------------
# positional filters: "cavity", "cylinder:60", ... ; flags: --skip-ff
positional = String[]
skip_ff = "--skip-ff" in ARGS
for a in ARGS
    startswith(a, "--") || push!(positional, a)
end

jobs = JOBS
res_filter = Dict{String,Union{Nothing,Float64}}()
if !isempty(positional)
    wanted = String[]
    for p in positional
        parts = split(p, ':')
        length(parts) <= 2 || error("bad filter '$p' (use key or key:Re)")
        key = parts[1]
        key in getfield.(JOBS, :key) || error("unknown geometry '$key' " *
            "(choices: $(join(getfield.(JOBS, :key), ", ")))")
        push!(wanted, key)
        length(parts) == 2 && (res_filter[key] = parse(Float64, parts[2]))
    end
    jobs = [j for j in JOBS if j.key in wanted]
end

for job in jobs
    Res = get(res_filter, job.key, nothing)
    for Re in (Res === nothing ? job.Res : [Res])
        try
            run_job(job, Re; skip_ff)
        catch err
            @error "job $(job.key) Re=$Re failed" exception = err
        end
    end
end
